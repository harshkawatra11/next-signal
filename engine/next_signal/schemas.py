from __future__ import annotations

from datetime import date, datetime
from typing import Literal, Optional

from pydantic import BaseModel, Field

OriginClass = Literal[
    "company_filing", "company_ir", "exchange", "regulator_us", "regulator_in", "sec",
    "rating_agency", "industry_body", "market_data", "press", "aggregator", "peer_filing",
]
Grade = Literal["A", "B", "C", "D", "E", "F"]


class Document(BaseModel):
    doc_id: str  # sha1(url)[:12]
    kind: str  # results, presentation, transcript, annual_report, warning_letter, ...
    title: str
    url: str
    publisher: str
    origin_class: OriginClass
    published_at: Optional[datetime] = None  # point-in-time stamp; None => excluded from as_of runs
    fetched_at: datetime
    pages: int = 0
    reliability: Grade = "B"


class Anchor(BaseModel):
    doc_id: str
    page: Optional[int] = None
    quote: str = Field(max_length=300)  # verbatim text that contains the number or claim
    verified: bool = False  # True when quote found verbatim (whitespace-normalised) in the doc text


class Fact(BaseModel):
    fact_id: str
    metric: str  # e.g. "revenue_north_america", "beds_operational"
    period: str  # "Q1FY27", "FY26", or ISO date for events
    value: float
    unit: str  # "INR_cr", "USD_mn", "pct", "days", "beds", "count"
    anchor: Anchor
    entity: str  # NSE symbol (company or peer)


class Event(BaseModel):
    event_id: str
    date: date
    kind: str  # fda_warning_letter, import_alert, anda_approval, recall, filing, guidance, news_first_seen, price_move, ...
    title: str
    origin_class: OriginClass
    url: str
    anchor: Optional[Anchor] = None


class MetricValue(BaseModel):
    metric_id: str
    period: str
    value: float
    unit: str
    inputs: list[str] = []  # fact_ids
    formula: str = ""  # human-readable formula string from the registry


class Anomaly(BaseModel):
    anomaly_id: str
    metric_id: str
    description: str
    peer_z: Optional[float] = None
    changepoint_period: Optional[str] = None
    trend_t: Optional[float] = None
    materiality_pct: Optional[float] = None
    score: float


class Prediction(BaseModel):
    metric_id: str
    direction: Literal["up", "down", "flat", "present", "absent"]
    where_to_check: str


class Hypothesis(BaseModel):
    hyp_id: str
    angle_id: str
    statement: str
    mechanism: str
    predictions: list[Prediction] = []
    disconfirmers: list[str] = []
    is_rival_of: Optional[str] = None  # rivals generated by Challenge point at their main hypothesis
    status: Literal["proposed", "survived", "downgraded", "killed"] = "proposed"
    kill_reason: Optional[str] = None


class Hypotheses(BaseModel):
    """Wrapper for structured-output calls: some json_schema implementations reject a top-level array."""

    items: list[Hypothesis] = []


class TestResult(BaseModel):
    hyp_id: str
    test_id: str  # T1..T9
    applicable: bool
    passed: Optional[bool] = None
    detail: str
    evidence_ids: list[str] = []
    plain: str = ""


class Contradiction(BaseModel):
    con_id: str
    type: Literal["numeric", "narrative_vs_number", "temporal", "cross_channel", "aggregator_vs_primary"]
    claim: str
    side_a: str
    side_b: str
    anchors: list[Anchor] = []
    ruling: str
    resolved: bool = False


class EvidenceItem(BaseModel):
    ev_id: str
    doc_id: str
    title: str
    url: str
    publisher: str
    origin_class: OriginClass
    reliability: Grade
    published_at: Optional[datetime] = None
    supports: list[str] = []  # hyp_ids
    contradicts: list[str] = []
    anchor: Anchor


class Claim(BaseModel):
    claim_id: str
    text: str
    evidence_ids: list[str] = []
    number_ids: list[str] = []


class NumberBlock(BaseModel):
    number_id: str
    label: str
    value: float
    unit: str
    period: str
    formula: str
    inputs: list[str] = []
    display: str  # preformatted, Indian notation


class TimelinePoint(BaseModel):
    date: date
    label: str
    kind: str
    event_id: Optional[str] = None
    is_changepoint: bool = False


class Falsification(BaseModel):
    statement: str
    metric_id: str
    comparator: Literal[">", "<", ">=", "<=", "=="]
    threshold: float
    periods_required: int
    next_check: date
    check_source: str
    plain: str = ""


class StrengthBreakdown(BaseModel):
    independence: float
    reliability: float
    corroboration: float
    survival: float
    persistence: float
    penalties: float
    total: float
    label: Literal["Strong", "Moderate", "Weak"]
    reasoning: list[str] = []


class Discovery(BaseModel):
    sentence: str = Field(max_length=360)
    why_it_matters: list[str] = Field(min_length=3, max_length=5)
    evidence: list[EvidenceItem]
    timeline: list[TimelinePoint]
    numbers: list[NumberBlock]
    counterargument: str
    counter_evidence_ids: list[str] = []
    falsification: Falsification
    strength: StrengthBreakdown
    claims: list[Claim] = []
    novelty: float = 0.0  # 0..1
    angle_id: str
    hyp_id: str = ""


class RunMeta(BaseModel):
    run_id: str
    symbol: str
    company: str
    sub_industry: str
    as_of: date
    started_at: datetime
    finished_at: Optional[datetime] = None
    runtime_s: Optional[float] = None
    llm_calls: int = 0
    llm_provider_mix: dict[str, int] = {}
    sources_hit: int = 0
    documents: int = 0
    status: Literal["running", "done", "failed", "partial"] = "running"


class ExtractedFact(BaseModel):
    """llm/prompts/extract.md output item, before it becomes a Fact (which requires an entity and a
    verified anchor; the quote here is checked against the source page by docs/anchors.py after the
    LLM call, not trusted blindly)."""

    metric: str
    period: str
    value: float
    unit: str
    page: Optional[int] = None
    quote: str


class ExtractedFacts(BaseModel):
    items: list[ExtractedFact] = []


class NarrativeClaim(BaseModel):
    claim: str
    metric_id_guess: str
    polarity: int  # +1, -1, or 0
    period: str
    quote: str
    page: Optional[int] = None


class NarrativeClaims(BaseModel):
    items: list[NarrativeClaim] = []


class DisconfirmQueries(BaseModel):
    items: list[str] = Field(min_length=1, max_length=3)


class EvidenceJudgement(BaseModel):
    item_index: int
    verdict: Literal["supports", "contradicts", "irrelevant"]
    quote: Optional[str] = None
    reasoning: Optional[str] = None


class EvidenceJudgements(BaseModel):
    items: list[EvidenceJudgement] = []


class ACHCell(BaseModel):
    evidence_index: int
    hypothesis_id: str
    glyph: Literal["CC", "C", "N", "I", "II"]


class ACHCells(BaseModel):
    items: list[ACHCell] = []


class DiscoveryText(BaseModel):
    """llm/prompts/write_discovery.md output: the prose half of a Discovery. pipeline/prove.py
    combines this with the already-computed numbers/evidence/timeline/falsification/strength to build
    the full schemas.Discovery, after llm/guards.py validates every number in this text traces back to
    an allowed source."""

    sentence: str = Field(max_length=360)
    why_it_matters: list[str] = Field(min_length=3, max_length=5)
    claims: list[Claim] = []
    counterargument: str


class SeriesPoint(BaseModel):
    period: str
    period_end: date
    value: float


class Series(BaseModel):
    entity: str  # NSE symbol, subject or a peer
    metric_id: str
    unit: str
    points: list[SeriesPoint] = []
    changepoint_period: Optional[str] = None


class FinancialRow(BaseModel):
    """One quarter's raw P&L line items, in INR crore, traced to the XBRL filing it came from."""

    period: str  # "Q3FY25"
    period_end: date
    values: dict[str, float]  # raw item name (revenue, cogs, ebitda, pat, ...) -> value
    doc_id: str


class Report(BaseModel):
    meta: RunMeta
    discovery: Optional[Discovery] = None
    runners_up: list[Hypothesis] = []  # survived but not chosen
    killed: list[Hypothesis] = []
    tests: list[TestResult] = []
    ach: dict = {}  # {"hypotheses":[...], "evidence":[...], "cells":[[score,...]]}
    contradictions: list[Contradiction] = []
    documents: list[Document] = []
    events: list[Event] = []
    metrics: list[MetricValue] = []
    anomalies: list[Anomaly] = []
    angles_considered: list[dict] = []  # {angle_id, score, reason}
    trace: list[dict] = []  # ordered run events for replay
    facts_count: int = 0
    financials: list[FinancialRow] = []  # subject's quarterly P&L, newest first
    series: list[Series] = []  # subject and peer series for every computed metric
    peers: list[str] = []
    stage_ms: dict[str, int] = {}
    glossary: dict[str, str] = {}
    peer_names: dict[str, str] = {}
